"""Generate the predeclared repeated-block benchmark family; no model outputs."""
import argparse
import hashlib
import json
from pathlib import Path
import shutil

import numpy as np
from osgeo import gdal, osr


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--sizes", type=int, nargs="+", default=[256, 1024, 2048, 3600])
    parser.add_argument("--output", type=Path, default=Path("tests/fixtures/generated/benchmarks"))
    args = parser.parse_args()
    if any(size < 32 for size in args.sizes):
        parser.error("Sizes must support the full 32-pixel geometry motif")
    gdal.UseExceptions()
    root = Path(__file__).resolve().parents[1]
    original = root / "tests/reference/small_original_cpu/scene"
    for size in args.sizes:
        path = args.output / f"repeated_block_{size}"
        path.mkdir(parents=True, exist_ok=False)
        dem = np.full((size, size), 3, dtype=np.float32)
        building = dem.copy()
        trees = np.zeros_like(dem)
        for row in range(0, size, 32):
            for col in range(0, size, 32):
                building[row+12:row+19, col+14:col+22] += 10
                trees[row+7:row+10, col+6:col+9] = 8
                trees[row+22:row+25, col+25:col+28] = 6
        # Retain the small fixture's geographic centre, projected metres and
        # resolution. Each scene is one distinct logical domain, never subtiles.
        transform = (583017.5 - size / 2, 1.0, 0.0, 4506984.0 + size / 2, 0.0, -1.0)
        srs = osr.SpatialReference()
        srs.ImportFromEPSG(32618)
        for filename, values in (("DEM.tif", dem), ("Building_DSM.tif", building), ("Trees.tif", trees)):
            ds = gdal.GetDriverByName("GTiff").Create(str(path / filename), size, size, 1, gdal.GDT_Float32)
            ds.SetGeoTransform(transform)
            ds.SetProjection(srs.ExportToWkt())
            ds.GetRasterBand(1).WriteArray(values)
            ds = None
            check = gdal.Open(str(path / filename))
            assert np.array_equal(check.ReadAsArray(), values)
            assert check.GetGeoTransform() == transform
            check = None
        shutil.copyfile(original / "met.txt", path / "met.txt")
        inputs = {p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted(path.iterdir())}
        kwargs = json.loads((root / "reports/initial_kwargs.json").read_text())
        kwargs.update(base_path=".", own_met_file="met.txt", tile_size=3600, overlap=20)
        (path / "kwargs.json").write_text(json.dumps(kwargs, indent=2) + "\n")
        manifest = {"evidence_class": "synthetic_input_fixture_not_reference_output",
                    "fixture_id": path.name, "files_sha256": inputs,
                    "fixture_sha256": hashlib.sha256(json.dumps(inputs, sort_keys=True).encode()).hexdigest(),
                    "generator_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
                    "rows": size, "cols": size, "transform": transform, "epsg": 32618,
                    "timesteps": 24, "patch_option": 2, "tile_size": 3600, "overlap": 20,
                    "building_fraction": float(np.mean(building - dem >= 2)),
                    "canopy_fraction": float(np.mean(trees > 0)),
                    "visible_output_fraction": float(np.mean(building - dem < 2)),
                    "limitations": ["Synthetic fixed-height geometry; real and tall/dense scenes remain required",
                                    "No baseline or candidate outputs generated by this tool"]}
        (path / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
        print(path, manifest["fixture_sha256"], flush=True)


if __name__ == "__main__":
    main()
